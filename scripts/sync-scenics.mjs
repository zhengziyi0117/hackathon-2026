import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=async path=>JSON.parse(await readFile(resolve(root,path),'utf8'));
const catalog=await read('scenics/catalog.json');
const validId=id=>typeof id==='string'&&/^[a-z][a-z0-9-]*$/.test(id);
if(!Array.isArray(catalog.scenics)||!catalog.scenics.length||new Set(catalog.scenics).size!==catalog.scenics.length||!catalog.scenics.every(validId))throw Error('Invalid scenic catalog');
const lines=['// Generated by npm run sync:scenics. Edit scenics/catalog.json and package JSON instead.'];
let count=0;
function add(path){const name='data'+count++;lines.push(`import ${name} from ${JSON.stringify('../../'+path)} with {type:'json'};`);return name;}
const packages=[];
for(const id of catalog.scenics){
 const base='scenics/'+id,m=await read(base+'/manifest.json');
 if(m.id!==id||!Array.isArray(m.spots)||!m.spots.every(validId)||new Set(m.spots).size!==m.spots.length)throw Error('Invalid scenic manifest: '+id);
 const manifest=add(base+'/manifest.json'),assets=add(base+'/assets.json');
 const map=Object.fromEntries(['manifest','geography','layout','interaction'].map(k=>[k,add(base+'/map/'+k+'.json')]));
 const spots=m.spots.map(spot=>`{content:${add(base+'/spots/'+spot+'/spot.json')},assets:${add(base+'/spots/'+spot+'/assets.json')}}`);
 packages.push(`{manifest:${manifest},assets:${assets},map:{${Object.entries(map).map(([k,v])=>k+':'+v).join(',')}},spots:[${spots.join(',')}]}`);
}
lines.push(`export const packages=[${packages.join(',\n')}];`);
const file=resolve(root,'src/content/generated-catalog.js'),text=lines.join('\n')+'\n';
if(process.argv.includes('--check')){
 if(await readFile(file,'utf8').catch(()=>'')!==text)throw Error('Scenic registry is stale. Run npm run sync:scenics.');
}else await writeFile(file,text);
console.log('Scenic registry: '+catalog.scenics.join(', '));
